#!/usr/bin/env python3
"""
Update benchmark tables in `relatorio.tex` using data from a benchmark CSV.
"""

from __future__ import annotations

import argparse
import csv
import re
import sys
from pathlib import Path

TABLE_LABELS = {
    "tab:bench_2f": 1,
    "tab:bench_fplus1": 2,
    "tab:bench_quicksort": 3,
}

ROW_PATTERN = re.compile(
    r"^(\s*)(Ascendente|Descendente|Desordenado)(\s*&\s*[^&]+?\s*&\s*)([0-9.]+)(\s*&.*?)(\\\\.*)$"
)
LABEL_PATTERN = re.compile(r"\\label\{(tab:[^}]+)\}")


def format_int_br(raw: str) -> str:
    """Format an integer string with '.' as thousands separator (e.g. 471705 -> 471.705)."""
    raw = raw.strip()
    if not raw:
        return "--"
    try:
        value = int(round(float(raw)))
    except ValueError:
        return "--"
    return f"{value:,}".replace(",", ".")


def format_ms(raw: str) -> str:
    """Format a millisecond float string to 2 decimal places."""
    raw = raw.strip()
    if not raw:
        return "--"
    try:
        value = float(raw)
    except ValueError:
        return "--"
    return f"{value:.2f}"


def load_csv(csv_path: Path) -> dict[tuple[int, str, int], dict[str, str]]:
    """Load CSV rows indexed by (algorithm_id, situation_name, quantity)."""
    records: dict[tuple[int, str, int], dict[str, str]] = {}
    with csv_path.open("r", encoding="utf-8", newline="") as fh:
        reader = csv.DictReader(fh)
        for row in reader:
            try:
                alg = int(row["algorithm"])
                sit_name = row["situation_name"].strip()
                qty = int(row["quantity"])
            except (KeyError, ValueError):
                continue
            records[(alg, sit_name, qty)] = row
    return records


def build_metric_cells(row: dict[str, str], alg: int) -> list[str]:
    """Return the formatted LaTeX metric cells for a benchmark row."""
    num_cols = 6 if alg == 3 else 10
    status = row.get("status", "").strip().lower()
    if status == "timeout":
        return [r"\texttt{Timeout}"] * num_cols
    if status == "error":
        return [r"\texttt{Erro}"] * num_cols

    if alg == 3:
        return [
            format_ms(row.get("phase2_time_p50_ms", "")),
            format_ms(row.get("phase2_time_p75_ms", "")),
            format_ms(row.get("phase2_time_p99_ms", "")),
            format_int_br(row.get("phase2_reads_p50", "")),
            format_int_br(row.get("phase2_writes_p50", "")),
            format_int_br(row.get("comparisons_p50", "")),
        ]

    return [
        format_ms(row.get("phase1_time_p50_ms", "")),
        format_ms(row.get("phase1_time_p75_ms", "")),
        format_ms(row.get("phase1_time_p99_ms", "")),
        format_int_br(row.get("phase1_reads_p50", "")),
        format_int_br(row.get("phase1_writes_p50", "")),
        format_ms(row.get("phase2_time_p50_ms", "")),
        format_ms(row.get("phase2_time_p75_ms", "")),
        format_ms(row.get("phase2_time_p99_ms", "")),
        format_int_br(row.get("phase2_reads_p50", "")),
        format_int_br(row.get("comparisons_p50", "")),
    ]


def update_tex_content(tex_content: str, records: dict[tuple[int, str, int], dict[str, str]]) -> tuple[str, int]:
    """Update matching table rows in `tex_content` and return (new_content, updated_count)."""
    lines = tex_content.splitlines(keepends=True)
    updated_lines: list[str] = []
    current_alg: int | None = None
    updated_count = 0

    for line in lines:
        label_match = LABEL_PATTERN.search(line)
        if label_match:
            label = label_match.group(1)
            if label in TABLE_LABELS:
                current_alg = TABLE_LABELS[label]

        if r"\end{table}" in line:
            current_alg = None

        if current_alg is not None:
            row_match = ROW_PATTERN.match(line.rstrip("\r\n"))
            if row_match:
                indent, sit_name, middle, qty_str, _metrics_part, line_end = row_match.groups()
                qty = int(qty_str.replace(".", ""))
                record = records.get((current_alg, sit_name, qty))
                if record is not None:
                    cells = build_metric_cells(record, current_alg)
                    newline = "\n" if line.endswith("\n") else ""
                    new_line = (
                        f"{indent}{sit_name}{middle}{qty_str} & "
                        + " & ".join(cells)
                        + f" {line_end}{newline}"
                    )
                    updated_lines.append(new_line)
                    updated_count += 1
                    continue

        updated_lines.append(line)

    return "".join(updated_lines), updated_count


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Update LaTeX benchmark tables in relatorio.tex from CSV results."
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("results/benchmark.csv"),
        help="Input CSV file generated by run_benchmarks.py (default: results/benchmark.csv)",
    )
    parser.add_argument(
        "--tex",
        type=Path,
        default=Path("relatorio.tex"),
        help="Path to LaTeX report file (default: relatorio.tex)",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=None,
        help="Optional output .tex path (default: overwrite --tex)",
    )
    args = parser.parse_args()

    if not args.csv.exists():
        print(f"Error: CSV file not found at '{args.csv}'", file=sys.stderr)
        return 1
    if not args.tex.exists():
        print(f"Error: LaTeX file not found at '{args.tex}'", file=sys.stderr)
        return 1

    records = load_csv(args.csv)
    tex_content = args.tex.read_text(encoding="utf-8")
    new_content, updated_count = update_tex_content(tex_content, records)

    output_path = args.output or args.tex
    output_path.write_text(new_content, encoding="utf-8")
    print(f"Updated {updated_count} table rows in {output_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
